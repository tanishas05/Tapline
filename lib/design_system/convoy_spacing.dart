/// Consistent spacing scale used across Convoy's layouts, so gaps and
/// padding are chosen from one small set of values instead of
/// one-off numbers scattered through widgets.
class ConvoySpacing {
  ConvoySpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 16;
  static const double lg = 24;
  static const double xl = 32;
  static const double xxl = 48;
}
